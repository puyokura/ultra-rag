"""Deterministic profile and constraint composition.

The architecture permits a delayed model-written profile but forbids losing a
new prohibition or resurrecting a corrected/forgotten policy. This generator is
therefore deterministic: it renders every adopted, auto-loaded memory verbatim
with conditions, exceptions, and provenance. It never summarizes a condition
away and never includes superseded, forgotten, or deleted records.
"""

from __future__ import annotations

from collections import defaultdict

from contracts.models import MemoryRecord

KIND_TITLES = {
    "philosophy": "思想",
    "design_principle": "設計理念",
    "preference": "好み・判断の優先順位",
    "lesson": "共通の教訓",
    "project_decision": "プロジェクトの決定",
}
CONSTRAINT_KINDS = ("prohibition", "requirement")
CORE_KINDS = ("philosophy", "design_principle", "preference")


def _applicable(records: list[MemoryRecord]) -> list[MemoryRecord]:
    rows = [
        record
        for record in records
        if record.status == "adopted"
        and record.autoload
        and record.kind not in CONSTRAINT_KINDS
        and record.scope in ("personal", "shared_lesson")
    ]
    unique: list[MemoryRecord] = []
    seen: set[tuple] = set()
    for record in rows:
        key = (
            record.statement.strip(),
            record.kind,
            record.scope,
            record.project_id,
            tuple(record.conditions),
            tuple(record.exceptions),
        )
        if key in seen:
            continue
        seen.add(key)
        unique.append(record)
    return unique


def _constraints(records: list[MemoryRecord]) -> list[MemoryRecord]:
    return [
        record
        for record in records
        if record.status == "adopted"
        and record.autoload
        and record.kind in CONSTRAINT_KINDS
        and record.scope != "session"
    ]


def _meta(record: MemoryRecord, project_id: str | None = None) -> str:
    bits = [f"`{record.id}` rev {record.revision}", f"scope={record.scope}"]
    if record.project_id:
        bits.append(f"project={record.project_id}")
    if record.conditions:
        bits.append("適用条件: " + " / ".join(record.conditions))
    if record.exceptions:
        bits.append("例外: " + " / ".join(record.exceptions))
    if record.source_refs:
        sources = []
        for ref in record.source_refs:
            pieces = [ref.session_id or "", ref.message_id or ""]
            label = ":".join(piece for piece in pieces if piece) or ref.note or "source"
            if ref.start is not None and ref.end is not None:
                label += f" [{ref.start}:{ref.end}]"
            sources.append(label)
        bits.append("出典: " + ", ".join(sources))
    return " (" + "; ".join(bits) + ")"


def _render_statement(record: MemoryRecord) -> str:
    lines = record.statement.strip().splitlines() or [""]
    rendered = "- " + lines[0]
    for line in lines[1:]:
        rendered += "\n  " + line
    return rendered


def render_profile(records: list[MemoryRecord], revision: int) -> str:
    adopted = _applicable(records)
    lines = [
        "# 個人プロフィール",
        "",
        f"<!-- generated by ultra-RAG from revision {revision}; "
        "every adopted auto-loaded philosophy/design/preference/lesson record is rendered verbatim -->",
        "",
    ]
    if not adopted:
        lines.append("(まだ採用済みの人物像記憶はない)")
        lines.append("")
    by_kind: dict[str, list[MemoryRecord]] = defaultdict(list)
    for record in adopted:
        by_kind[record.kind].append(record)
    for kind in ("philosophy", "design_principle", "preference", "lesson", "project_decision"):
        items = by_kind.get(kind)
        if not items:
            continue
        title = KIND_TITLES.get(kind, kind)
        lines.append(f"## {title}")
        lines.append("")
        for record in sorted(items, key=lambda item: (item.scope, item.project_id or "", item.recorded_at, item.id)):
            prefix = f"[{record.project_id}] " if record.scope == "project" and record.project_id else ""
            body = _render_statement(record)
            if prefix:
                body = body[:2] + prefix + body[2:]
            lines.append(body + _meta(record))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_constraints(records: list[MemoryRecord], revision: int) -> str:
    active = _constraints(records)
    lines = [
        "# 禁止・必須事項",
        "",
        f"<!-- generated by ultra-RAG from revision {revision}; "
        "all adopted prohibition/requirement records are rendered, independent of search ranking -->",
        "",
    ]
    if not active:
        lines.append("(適用される禁止・必須事項はない)")
        lines.append("")
        return "\n".join(lines).rstrip() + "\n"
    grouped: dict[str, dict[str, list[MemoryRecord]]] = {
        "prohibition": defaultdict(list),
        "requirement": defaultdict(list),
    }
    for record in active:
        grouped[record.kind][record.scope].append(record)
    titles = {"prohibition": "禁止", "requirement": "必須"}
    for kind in ("prohibition", "requirement"):
        lines.append(f"## {titles[kind]}")
        lines.append("")
        for scope in ("personal", "shared_lesson", "project", "session"):
            items = grouped[kind].get(scope)
            if not items:
                continue
            if scope == "project":
                by_project: dict[str, list[MemoryRecord]] = defaultdict(list)
                for record in items:
                    by_project[record.project_id or "(未指定)"].append(record)
                for project_id, project_items in sorted(by_project.items()):
                    lines.append(f"### プロジェクト {project_id}")
                    lines.append("")
                    for record in sorted(project_items, key=lambda item: (item.recorded_at, item.id)):
                        lines.append(_render_statement(record) + _meta(record))
                    lines.append("")
            else:
                scope_label = {"personal": "個人共通", "shared_lesson": "共通の教訓", "session": "セッション限定"}[scope]
                lines.append(f"### {scope_label}")
                lines.append("")
                for record in sorted(items, key=lambda item: (item.recorded_at, item.id)):
                    lines.append(_render_statement(record) + _meta(record))
                lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_project_overview(project_id: str, memories: list[MemoryRecord], sessions: list[str]) -> str:
    lines = [
        f"# プロジェクト {project_id}",
        "",
        f"- 記憶: {len(memories)} 件",
        f"- セッション書き溜め: {len(sessions)} 件",
        "",
    ]
    if memories:
        lines.append("## 記憶一覧")
        lines.append("")
        for record in sorted(memories, key=lambda item: (item.status, item.recorded_at, item.id)):
            lines.append(
                f"- `{record.id}` [{record.kind}/{record.status}] {record.statement.splitlines()[0]}"
            )
        lines.append("")
    if sessions:
        lines.append("## セッション")
        lines.append("")
        for session_id in sorted(sessions):
            lines.append(f"- `{session_id}`")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def applicable_constraints(records: list[MemoryRecord], project_id: str | None) -> list[MemoryRecord]:
    """Constraints that must be injected for one request, never truncated by rank."""
    result = []
    for record in _constraints(records):
        if record.scope == "project" and record.project_id != project_id:
            continue
        result.append(record)
    return sorted(result, key=lambda item: (item.kind, item.scope, item.project_id or "", item.id))


def render_core_profile(records: list[MemoryRecord], revision: int) -> str:
    """Only the kinds injected on every request; lessons are fetched on demand."""
    return render_profile([record for record in records if record.kind in CORE_KINDS], revision)


def profile_memories(records: list[MemoryRecord]) -> list[MemoryRecord]:
    return sorted(_applicable(records), key=lambda item: (item.kind, item.scope, item.id))
